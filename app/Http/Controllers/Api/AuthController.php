<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\User;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Hash;
use Illuminate\Validation\ValidationException;
use App\Helpers\AdminNotificationHelper;


class AuthController extends Controller
{
    public function register(Request $request)
    {
        $request->validate([
            'name' => ['required', 'string', 'max:255'],
            'email' => ['required', 'email', 'unique:users,email'],
            'password' => ['required', 'string', 'min:6', 'confirmed'],
        ]);

        $user = User::create([
            'name' => $request->name,
            'email' => $request->email,
            'password' => Hash::make($request->password),
            'usertype' => 'user',
        ]);

        $token = $user->createToken($user->usertype . '_token')->plainTextToken;

        AdminNotificationHelper::create(
            'New user registered',
            $user->name . ' has created an account.',
            'user_registered',
            '/admin/users',
            ['user_id' => $user->id]
        );

        return response()->json([
            'success' => true,
            'message' => 'Account created successfully.',
            'user' => [
                'id' => $user->id,
                'name' => $user->name,
                'email' => $user->email,
                'usertype' => $user->usertype,
            ],
            'token' => $token,
            'redirect_to' => '/account',
        ], 201);
    }

    public function login(Request $request)
    {
        $request->validate([
            'email' => ['required', 'email'],
            'password' => ['required', 'string'],
        ]);

        $user = User::where('email', $request->email)->first();

        if (!$user || !Hash::check($request->password, $user->password)) {
            throw ValidationException::withMessages([
                'email' => ['Credentials si sahihi.'],
            ]);
        }

        $user->tokens()->delete();

        $token = $user->createToken($user->usertype . '_token')->plainTextToken;
        AdminNotificationHelper::create(
            'User login',
            $user->name . ' has logged in.',
            'user_login',
            '/admin/users',
            ['user_id' => $user->id]
        );

        return response()->json([
            'success' => true,
            'message' => 'Login successful.',
            'user' => [
                'id' => $user->id,
                'name' => $user->name,
                'email' => $user->email,
                'usertype' => $user->usertype,
            ],
            'token' => $token,
            'redirect_to' => $user->usertype === 'admin' ? '/admin/dashboard' : '/account',
        ]);
    }

    public function logout(Request $request)
    {
        $request->user()->currentAccessToken()->delete();

        return response()->json([
            'success' => true,
            'message' => 'Logged out successfully.',
        ]);
    }
}

